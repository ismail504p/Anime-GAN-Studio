import os
import io
import numpy as np
import streamlit as st
from PIL import Image
import tensorflow as tf

MODEL_PATH = os.path.join(os.path.dirname(__file__), "generator.h5")

st.set_page_config(page_title="Anime GAN Studio", page_icon="🎨", layout="centered")
st.title("🎨 Anime GAN Studio")
st.write("Generate an anime-style image with your trained GAN.")

@st.cache_resource
def load_generator():
    return tf.keras.models.load_model(MODEL_PATH, compile=False)

try:
    generator = load_generator()
except Exception as exc:
    st.error("Could not load generator.h5. Check the TensorFlow/Keras installation in README.md.")
    st.exception(exc)
    st.stop()

with st.form("generate_form"):
    character_name = st.text_input("Anime character name", placeholder="e.g. Naruto, Sakura, or my original character")
    seed = st.number_input("Random seed (same seed = repeatable result)", min_value=0, max_value=2_147_483_647, value=42, step=1)
    submitted = st.form_submit_button("✨ Generate Anime", type="primary", use_container_width=True)

if submitted:
    rng = np.random.default_rng(int(seed))
    noise = rng.normal(0, 1, size=(1, 100)).astype(np.float32)
    try:
        generated = generator.predict(noise, verbose=0)[0]
        # The final layer uses tanh, so expected pixel values are in [-1, 1].
        generated = np.clip((generated + 1.0) * 127.5, 0, 255).astype(np.uint8)
        image = Image.fromarray(generated)
        st.subheader(character_name.strip() or "Generated anime character")
        st.image(image, caption="Generated by your trained GAN", use_container_width=False)
        buf = io.BytesIO()
        image.save(buf, format="PNG")
        st.download_button("⬇️ Download image", data=buf.getvalue(), file_name="anime_character.png", mime="image/png", use_container_width=True)
        st.caption(f"Seed: {int(seed)}")
    except Exception as exc:
        st.error("Generation failed. The model's input/output shape may differ from the expected setup.")
        st.exception(exc)

with st.expander("Important: what the character name does"):
    st.write("This generator takes a 100-number noise vector as input and does not accept text or character labels. The name is used as the result title only; it does not control the character's identity. To generate a specific named character, you would need a conditional GAN trained with character labels, or a text-conditioned image model.")
